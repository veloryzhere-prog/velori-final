import { createSourceZip } from "./zip-store.mjs";
import type { Page, Project } from "./model.ts";
import { parseSourceFiles } from "./multi-file.ts";
export const scriptLiteral = (v: unknown) =>
  JSON.stringify(v)
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
const escape = (s: string) =>
  s.replace(
    /[&<>"']/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!,
  );
export function pageDocument(
  page: Page,
  title: string,
  channel: string,
  paths: string[],
  motion = true,
) {
  const bridge = `(()=>{const paths=${scriptLiteral(paths)};const send=(kind,message)=>parent.postMessage({source:'velori-artifact',channel:${scriptLiteral(channel)},kind,message:String(message).slice(0,600)},'*');addEventListener('error',e=>send('error',e.message));addEventListener('unhandledrejection',()=>send('error','An asynchronous action failed.'));addEventListener('load',()=>send('ready','Preview ready'));document.addEventListener('click',e=>{const link=e.target.closest?.('a');if(!link)return;const href=link.getAttribute('href')||'';const path=href.startsWith('#')?href.slice(1):href.replace(/^\\//,'').replace(/\\.html$/,'');if(paths.includes(path)){e.preventDefault();send('navigate',path)}})})();`;
  const css =
    page.css +
    (!motion
      ? "\n*,*::before,*::after{animation:none!important;transition:none!important;scroll-behavior:auto!important}"
      : "");
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="referrer" content="no-referrer"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; media-src data: blob:; font-src data:; connect-src 'none'; frame-src 'none'; object-src 'none'; worker-src 'none'; base-uri 'none'; form-action 'none'"><title>${escape(title)}</title><style>body{margin:0;font-family:system-ui,sans-serif}*{box-sizing:border-box}</style><script>${bridge}(()=>{const s=document.createElement('style');s.textContent=${scriptLiteral(css)};document.head.append(s)})();<\/script></head><body>${page.html}<script>(()=>{const s=document.createElement('script');s.textContent=${scriptLiteral(page.js)};document.body.append(s)})();<\/script></body></html>`;
}
export function appDocument(pages: Page[], title: string, motion = true) {
  const channel = "velori-export-v2";
  const paths = pages.map((p) => p.path);
  const docs = Object.fromEntries(
    pages.map((p) => [p.path, pageDocument(p, title, channel, paths, motion)]),
  );
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="referrer" content="no-referrer"><title>${escape(title)}</title><style>html,body{margin:0;width:100%;height:100%;background:white}iframe{display:block;width:100%;height:100dvh;border:0}</style></head><body><iframe id="canvas" title="${escape(title)}" sandbox="allow-scripts" referrerpolicy="no-referrer"></iframe><script>(()=>{const docs=${scriptLiteral(docs)};const frame=document.getElementById('canvas');function show(){const path=location.hash.slice(1);frame.srcdoc=docs[Object.hasOwn(docs,path)?path:'index']}addEventListener('hashchange',show);addEventListener('message',e=>{if(e.source!==frame.contentWindow||e.origin!=='null'||e.data?.source!=='velori-artifact'||e.data?.channel!==${scriptLiteral(channel)}||e.data.kind!=='navigate'||!Object.hasOwn(docs,e.data.message))return;location.hash=e.data.message});show()})();<\/script></body></html>`;
}
export function sourceZip(project: Project): Blob {
  const paths = project.pages.map((page) => page.path);
  const files = parseSourceFiles(project.files);
  const multi = files.length > 0;
  const pagePrefix = multi ? "velori-static-preview/" : "";
  const entries: Array<[string, string]> = [
    [
      "README.md",
      `# ${project.title.replace(/[\r\n]/g, " ")}\n\n${
        multi
          ? "Multi-file source project generated by VELORI Forge AI. Project source files are at the archive root. Run npm install and npm run dev only after reviewing generated package scripts and dependencies. The isolated VELORI preview is provided as a separate static reference under velori-static-preview/.\n"
          : "Offline static HTML/CSS/JS project from VELORI Forge AI. Open index.html to preview all pages. Edit individual sources under pages/.\n"
      }
Project source is stored locally on the user's device. Generated code must be tested and checked for rights before distribution.\n`,
    ],
    [
      "project.json",
      JSON.stringify(
        {
          title: project.title,
          pages: project.pages,
          files,
          stack: project.stack ?? "static",
          history: project.history,
          format: "velori-artifact-v4",
        },
        null,
        2,
      ),
    ],
    [`${pagePrefix}index.html`, appDocument(project.pages, project.title)],
  ];
  for (const page of project.pages) {
    entries.push([
      `${pagePrefix}pages/${page.path}/index.html`,
      pageDocument(page, project.title, "velori-static-source", paths),
    ]);
    entries.push([`${pagePrefix}pages/${page.path}/style.css`, page.css]);
    entries.push([`${pagePrefix}pages/${page.path}/script.js`, page.js]);
  }
  // Project source takes precedence as an independent worktree; reject collisions.
  for (const file of files) {
    if (entries.some(([p]) => p.toLowerCase() === file.path.toLowerCase()))
      throw new Error(`Source file ${file.path} conflicts with a generated archive file.`);
    entries.push([file.path, file.content]);
  }
  return createSourceZip(entries);
}

export function downloadProject(project: Project, kind: "html" | "json" | "zip") {
  if (kind === "zip") {
    const url = URL.createObjectURL(sourceZip(project));
    const a = document.createElement("a");
    a.href = url;
    a.download = `${project.title.replace(/[^a-z0-9_-]/gi, "-").slice(0, 70) || "velori-project"}.zip`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
    return;
  }
  const content =
    kind === "html"
      ? appDocument(project.pages, project.title)
      : JSON.stringify(
          { ...project, format: "velori-artifact-v2", id: undefined, cloudUpdatedAt: undefined },
          null,
          2,
        );
  const url = URL.createObjectURL(
    new Blob([content], { type: kind === "html" ? "text/html;charset=utf-8" : "application/json" }),
  );
  const a = document.createElement("a");
  a.href = url;
  a.download = `${project.title.replace(/[^a-z0-9_-]/gi, "-").slice(0, 70) || "velori-app"}.${kind}`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
