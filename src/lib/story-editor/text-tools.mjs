export function getStoryAutoFontSize(text, baseSize, widthPercent, heightPercent) {
  const content = String(text ?? "").trim();
  const safeBase = Number.isFinite(baseSize) ? Math.min(Math.max(baseSize, 12), 160) : 48;
  const width = Math.max(10, Math.min(widthPercent, 100)) * 10.8;
  const height = Math.max(5, Math.min(heightPercent, 100)) * 19.2;
  if (!content) return safeBase;
  const words = content.split(/\s+/);
  for (let size = safeBase; size >= 12; size -= 1) {
    const maxChars = Math.max(1, Math.floor(width / (size * 0.56)));
    let lines = 1;
    let lineLength = 0;
    let fitsLongestWord = true;
    for (const word of words) {
      if (word.length > maxChars) fitsLongestWord = false;
      const nextLength = lineLength ? lineLength + 1 + word.length : word.length;
      if (nextLength > maxChars) {
        lines += 1;
        lineLength = word.length;
      } else {
        lineLength = nextLength;
      }
    }
    if (fitsLongestWord && lines * size * 1.2 <= height) return size;
  }
  return 12;
}

export function getStoryTextAnimationState(
  animation,
  elapsedSeconds,
  startAt,
  duration,
  delay = 0,
  loop = false,
) {
  if (animation === "none") return { visible: true, progress: 1 };
  const elapsed = Number.isFinite(elapsedSeconds) ? elapsedSeconds : 0;
  const start = Number.isFinite(startAt) ? Math.max(0, startAt) : 0;
  const safeDuration = Number.isFinite(duration) ? Math.max(0.1, duration) : 0.7;
  const safeDelay = Number.isFinite(delay) ? Math.max(0, delay) : 0;
  const animationStart = start + safeDelay;
  const time = elapsed - animationStart;
  const visible =
    animation === "fade-out" ? elapsed < animationStart + safeDuration : elapsed >= animationStart;
  const progress = loop
    ? (Math.max(0, time) % safeDuration) / safeDuration
    : Math.min(Math.max(time / safeDuration, 0), 1);
  return { visible, progress };
}

export function getStoryTextAnimationFrame(animation, progress, baseRotation = 0) {
  const p = Math.min(1, Math.max(0, Number.isFinite(progress) ? progress : 0));
  const frame = { opacity: 1, x: 0, y: 0, scale: 1, rotation: baseRotation };
  switch (animation) {
    case "fade-in":
    case "fade":
      frame.opacity = p;
      break;
    case "fade-out":
      frame.opacity = 1 - p;
      break;
    case "fade-in-out":
      frame.opacity = p < 0.5 ? p * 2 : (1 - p) * 2;
      break;
    case "slide-up":
      frame.y = (1 - p) * 48;
      frame.opacity = p;
      break;
    case "slide-down":
      frame.y = (p - 1) * 48;
      frame.opacity = p;
      break;
    case "slide-left":
      frame.x = (1 - p) * 48;
      frame.opacity = p;
      break;
    case "slide-right":
      frame.x = (p - 1) * 48;
      frame.opacity = p;
      break;
    case "slide":
      frame.y = (1 - p) * 34;
      frame.opacity = p;
      break;
    case "zoom-in":
      frame.scale = 0.35 + p * 0.65;
      frame.opacity = p;
      break;
    case "zoom-out":
      frame.scale = 1.5 - p * 0.5;
      frame.opacity = p;
      break;
    case "pop":
      frame.scale = 0.6 + Math.sin(p * Math.PI) * 0.5;
      break;
    case "bounce":
      frame.y = Math.sin(p * Math.PI * 3) * (1 - p) * 18;
      break;
    case "pulse":
      frame.scale = 0.92 + Math.sin(p * Math.PI * 2) * 0.08;
      break;
    case "rotate-in":
      frame.rotation = baseRotation - (1 - p) * 90;
      frame.scale = 0.85 + p * 0.15;
      frame.opacity = p;
      break;
    case "spin":
      frame.rotation = baseRotation + p * 360;
      break;
    case "float":
      frame.y = Math.sin(p * Math.PI * 2) * 8;
      break;
    default:
      break;
  }
  return frame;
}

export function getStoryTypewriterText(text, progress) {
  const content = String(text ?? "");
  const length = Math.floor(content.length * Math.min(Math.max(progress, 0), 1));
  return content.slice(0, length);
}
